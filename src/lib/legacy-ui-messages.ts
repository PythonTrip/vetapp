export const RU_TO_EN: Record<string, string> = Object.fromEntries(
  Object.entries(EN_TO_RU).map(([english, russian]) => [russian, english]),
);

export function translateLegacyText(value: string, locale: "ru" | "en"): string {
  const trimmed = value.trim();
  if (!trimmed) return value;

  let translated: string | undefined =
    locale === "ru"
      ? EN_TO_RU[trimmed]
      : RU_TO_EN[trimmed];

  if (!translated) {
    translated = translateDynamic(trimmed, locale);
  }

  if (!translated || translated === trimmed) return value;
  return value.replace(trimmed, translated);
}

function translateDynamic(value: string, locale: "ru" | "en"): string | undefined {
  if (locale === "ru") {
    const rules: Array<[RegExp, (...matches: string[]) => string]> = [
      [/^In (\d+) days$/, (_all, days) => `Через ${days} дн.`],
      [/^(\d+) scheduled$/, (_all, count) => `${count} запланировано`],
      [/^(\d+) visits$/, (_all, count) => `${count} визитов`],
      [/^(\d+) consultations$/, (_all, count) => `${count} консультаций`],
      [/^(\d+) patient(?:s)? need attention$/, (_all, count) => `${count} пациентов требуют внимания`],
      [/^· next in (\d+)d$/, (_all, days) => `· следующий через ${days} дн.`],
      [/^(\d+) min$/, (_all, minutes) => `${minutes} мин`],
      [/^(\d+) days$/, (_all, days) => `${days} дней`],
      [/^(\d+) kg$/, (_all, weight) => `${weight} кг`],
      [/^(\d+(?:[.,]\d+)?) kg\/wk$/, (_all, weight) => `${weight} кг/нед.`],
      [/^(\d+)% of caseload$/, (_all, value) => `${value}% от всех пациентов`],
    ];
    for (const [pattern, replacer] of rules) {
      const match = value.match(pattern);
      if (match) return replacer(...match);
    }
    return undefined;
  }

  const rules: Array<[RegExp, (...matches: string[]) => string]> = [
    [/^Через (\d+) дн\.$/, (_all, days) => `In ${days} days`],
    [/^(\d+) запланировано$/, (_all, count) => `${count} scheduled`],
    [/^(\d+) визитов$/, (_all, count) => `${count} visits`],
    [/^(\d+) консультаций$/, (_all, count) => `${count} consultations`],
    [/^(\d+) мин$/, (_all, minutes) => `${minutes} min`],
    [/^(\d+) дней$/, (_all, days) => `${days} days`],
    [/^(\d+) кг$/, (_all, weight) => `${weight} kg`],
  ];
  for (const [pattern, replacer] of rules) {
    const match = value.match(pattern);
    if (match) return replacer(...match);
  }
  return undefined;
}
