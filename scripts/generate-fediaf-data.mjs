// Generates src/lib/fediaf-data.ts from the FEDIAF 2025 CSV exports in docs/.
// FEDIAF Nutritional Guidelines, September 2025 edition.
//
//   node scripts/generate-fediaf-data.mjs
//
// Re-run whenever the docs/fediaf_2025_*.csv files change. The output is a
// self-contained TypeScript module so the app never parses CSV at runtime
// (mirrors how the NRC reference values are embedded in nutrition-analysis.ts).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const NUTRIENTS_CSV = path.join(root, "docs", "fediaf_2025_nutrients_1000kcal.csv");
const ENERGY_CSV = path.join(root, "docs", "fediaf_2025_energy_formulas.csv");
const OUT = path.join(root, "src", "lib", "fediaf-data.ts");

/** Minimal RFC-4180 CSV parser (handles quoted fields, escaped quotes, CRLF, BOM). */
function parseCSV(text) {
  const rows = [];
  let i = 0, field = "", row = [], inQ = false;
  text = text.replace(/^﻿/, "");
  while (i < text.length) {
    const c = text[i];
    if (inQ) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else inQ = false; }
      else field += c;
    } else {
      if (c === '"') inQ = true;
      else if (c === ",") { row.push(field); field = ""; }
      else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
      else if (c === "\r") { /* ignore */ }
      else field += c;
    }
    i++;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows;
}

function toObjects(csvText) {
  const rows = parseCSV(csvText).filter((r) => r.some((x) => x !== ""));
  const header = rows[0];
  return rows.slice(1).map((r) => Object.fromEntries(header.map((h, idx) => [h, r[idx] ?? ""])));
}

const num = (s) => {
  if (s == null || s === "") return null;
  const v = Number(String(s).replace(",", "."));
  return Number.isFinite(v) ? v : null;
};

// ─── Nutrient minimums per 1000 kcal ME ───────────────────────────
const nutrientRows = toObjects(fs.readFileSync(NUTRIENTS_CSV, "utf8"));
const stageMap = new Map();
let sourceUrl = "";
for (const r of nutrientRows) {
  const stageCode = r["stage_code"];
  if (!stageCode) continue;
  sourceUrl ||= r["source_url"] || "";
  if (!stageMap.has(stageCode)) {
    stageMap.set(stageCode, {
      code: stageCode,
      species: r["species_code"],
      labelRu: r["Стадия"],
      physiologicalState: r["physiological_state"] || null,
      merReference: r["MER_reference"] || null,
      sourceTable: r["source_table"] || null,
      sourcePage: num(r["source_page"]),
      nutrients: [],
    });
  }
  stageMap.get(stageCode).nutrients.push({
    code: r["nutrient_code"],
    category: r["category_code"],
    labelRu: r["Нутриент RU"],
    unit: r["Ед./1000 ккал ME"],
    min: num(r["min_value"]),
    minUpper: num(r["min_value_upper"]),
    established: r["is_established"] === "True",
    footnote: r["footnote"] || null,
    note: r["Примечание"] || null,
  });
}
const stages = [...stageMap.values()];

// ─── Energy (MER) formulas ────────────────────────────────────────
const energyRows = toObjects(fs.readFileSync(ENERGY_CSV, "utf8"));
const formulas = energyRows.map((r) => ({
  species: r["species_code"],
  phaseCode: r["phase_code"],
  labelRu: r["Стадия/условие"],
  formula: r["Формула ккал ME/сут"],
  range: r["Диапазон/альтернатива"] || null,
  params: r["Параметры"] || null,
  page: num(r["Страница"]),
  note: r["Примечание"] || null,
}));

// ─── Emit TypeScript ──────────────────────────────────────────────
const banner = `// AUTO-GENERATED by scripts/generate-fediaf-data.mjs — DO NOT EDIT BY HAND.
// Source: FEDIAF Nutritional Guidelines, September 2025 edition.
// Regenerate with: node scripts/generate-fediaf-data.mjs
`;

const body = `${banner}
export type FediafSpecies = "dog" | "cat";

/** One nutrient's minimum recommended allowance per 1000 kcal ME for a stage. */
export interface FediafNutrientMin {
  /** FEDIAF nutrient identifier, e.g. "calcium", "vitamin_a". */
  code: string;
  category: string;
  labelRu: string;
  /** Unit of \`min\` per 1000 kcal ME: "g" | "mg" | "µg" | "IU" | "ratio". */
  unit: string;
  /** Minimum per 1000 kcal ME; null when FEDIAF does not establish a value (NE). */
  min: number | null;
  /** Upper bound of the recommended range, when FEDIAF gives one. */
  minUpper: number | null;
  established: boolean;
  footnote: string | null;
  note: string | null;
}

export interface FediafStage {
  code: string;
  species: FediafSpecies;
  labelRu: string;
  physiologicalState: string | null;
  merReference: string | null;
  sourceTable: string | null;
  sourcePage: number | null;
  nutrients: FediafNutrientMin[];
}

/** A FEDIAF daily-energy (MER) formula for a species/physiological phase. */
export interface FediafEnergyFormula {
  species: FediafSpecies;
  phaseCode: string;
  labelRu: string;
  formula: string;
  range: string | null;
  params: string | null;
  page: number | null;
  note: string | null;
}

export const FEDIAF_SOURCE_URL = ${JSON.stringify(sourceUrl)};
export const FEDIAF_EDITION = "FEDIAF Nutritional Guidelines — сентябрь 2025";

export const FEDIAF_NUTRIENT_STAGES: FediafStage[] = ${JSON.stringify(stages, null, 2)};

export const FEDIAF_ENERGY_FORMULAS: FediafEnergyFormula[] = ${JSON.stringify(formulas, null, 2)};
`;

fs.writeFileSync(OUT, body, "utf8");
console.log(`Wrote ${path.relative(root, OUT)}`);
console.log(`  stages: ${stages.length}, energy formulas: ${formulas.length}`);
console.log(`  nutrient rows: ${nutrientRows.length}`);
